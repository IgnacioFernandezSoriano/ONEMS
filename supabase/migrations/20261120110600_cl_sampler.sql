-- Carrier Link fase 1, tarea 8: sorteo reproducible, muestra y paso a la base E2E.
-- Spec: docs/superpowers/specs/2026-11-19-carrier-link-design.md §5, D5, D6, D7, D9, D10, D11, D12, R15, R18.
--
-- cl_sample_stratum(lote, estrato): sortea entre los candidatos validos que dejo cl_ingest_batch, crea las muestras
-- (cl_samples + cl_sample_scans), las pasa a one_db (cl_transfer_sample) y escribe cl_sampling_runs. Idempotente.
-- cl_finish_batch(lote): cuando todos los estratos del lote estan sorteados, cierra lote, demanda y cuotas cumplidas.
-- La liquidacion de cuotas no cubiertas (cl_settle_quota) llega en la tarea 9, que reemplaza cl_finish_batch.
-- No toca allocation_plans, allocation_plan_details, transfer_to_one_db, el ETL RFID ni
-- recalculate_on_time_delivery_on_sla_change.

-- ---------------------------------------------------------------- orden de llegada de cada lectura
-- cl_ingest_batch elige el inicio con ORDER BY scan_at, is_end, r_ord (r_ord = posicion de la lectura en su estrato)
-- e inserta cl_batch_scans con ORDER BY s_ord, r_ord. La identidad se asigna en ese orden, asi que dentro de un
-- estrato row_ord ordena igual que r_ord y el muestreador desempata exactamente como la entrada.
ALTER TABLE public.cl_batch_scans ADD COLUMN row_ord bigint GENERATED BY DEFAULT AS IDENTITY;

-- ---------------------------------------------------------------- inicio y fin de cada envio (regla unica de D5)
-- Para las lecturas validas de un estrato de un lote devuelve, por lectura: si es de inicio / fin segun la foto de
-- la demanda (D13, con el modo del punto resuelto: D4) y, por item_id, la lectura elegida como inicio y como fin.
-- Es la misma regla que cl_ingest_batch (pasos 6-7):
--   * de inicio/fin: existe en start_points/end_points de la foto un punto con el mismo place_ref y el mismo modo
--     que el punto al que se resolvio la lectura (readers.carrier_mode_ref de cl_batch_scans.reader_id);
--   * inicio = primera lectura de inicio por (scan_at, is_end, orden de llegada);
--   * fin = ultima lectura de fin que no sea la de inicio (a igual hora, la que llego despues): mismo end_at que
--     max(scan_at) de la entrada.
-- La unica forma de divergir es cambiar el modo de un punto entre la entrada y el sorteo (el sorteo se llama justo
-- despues de la entrada); un candidato que asi pierda su inicio o su fin no se sortea.
-- Ademas marca, por lectura, el papel vivo del punto (origin/destination/both) en cualquier ciudad: R15, toda lectura
-- de inicio y de fin se guarda con la muestra aunque no encaje en la ruta pedida.
CREATE OR REPLACE FUNCTION public.cl_stratum_endpoints(p_batch_id uuid, p_stratum_id uuid)
 RETURNS TABLE (scan_id uuid, item_id text, row_ord bigint, scan_at timestamptz, reader_id uuid, place_ref text,
                mode_ref text, extra jsonb, city_id uuid, is_start boolean, is_end boolean,
                live_start boolean, live_end boolean, start_scan_id uuid, end_scan_id uuid)
 LANGUAGE sql
 STABLE
 SET search_path = public, extensions
AS $$
  WITH snap AS (
    SELECT sn.d
      FROM public.cl_batches b
      JOIN public.cl_demands dm ON dm.id = b.demand_id
     CROSS JOIN LATERAL jsonb_array_elements(dm.payload->'strata') sn(d)
     WHERE b.id = p_batch_id AND sn.d->>'stratum_id' = p_stratum_id::text
  ), rws AS (
    SELECT s.id, s.item_id, s.row_ord, s.scan_at, s.reader_id, s.place_ref, s.mode_ref, s.extra, pc.city_id,
           EXISTS (SELECT 1 FROM snap, jsonb_array_elements(snap.d->'start_points') p
                    WHERE p->>'place_ref' = s.place_ref AND (p->>'mode_ref') IS NOT DISTINCT FROM r.carrier_mode_ref) AS is_start,
           EXISTS (SELECT 1 FROM snap, jsonb_array_elements(snap.d->'end_points') p
                    WHERE p->>'place_ref' = s.place_ref AND (p->>'mode_ref') IS NOT DISTINCT FROM r.carrier_mode_ref) AS is_end,
           r.e2e_role IN ('origin','both') AS live_start,
           r.e2e_role IN ('destination','both') AS live_end
      FROM public.cl_batch_scans s
      JOIN public.readers r ON r.id = s.reader_id
      LEFT JOIN public.postal_centers pc ON pc.id = r.postal_center_id
     WHERE s.batch_id = p_batch_id AND s.stratum_id = p_stratum_id AND s.status = 'valid'
  ), st AS (
    SELECT DISTINCT ON (x.item_id) x.item_id, x.id AS start_id
      FROM rws x WHERE x.is_start
     ORDER BY x.item_id, x.scan_at, x.is_end, x.row_ord
  ), en AS (
    SELECT DISTINCT ON (x.item_id) x.item_id, x.id AS end_id
      FROM rws x JOIN st ON st.item_id = x.item_id
     WHERE x.is_end AND x.id <> st.start_id
     ORDER BY x.item_id, x.scan_at DESC, x.row_ord DESC
  )
  SELECT x.id, x.item_id, x.row_ord, x.scan_at, x.reader_id, x.place_ref, x.mode_ref, x.extra, x.city_id,
         x.is_start, x.is_end, x.live_start, x.live_end, st.start_id, en.end_id
    FROM rws x
    LEFT JOIN st ON st.item_id = x.item_id
    LEFT JOIN en ON en.item_id = x.item_id
$$;
REVOKE ALL ON FUNCTION public.cl_stratum_endpoints(uuid, uuid) FROM PUBLIC, anon, authenticated, service_role;

-- ---------------------------------------------------------------- paso de una muestra a one_db
-- Interna (sin grants). Ruta = carrier, producto y ciudades REALES de la muestra (D6). Con estandar: equivalencia
-- (D9) y on_time con los tiempos que calcula el trigger one_db_compute_transit (medido + equivalencia).
-- Sin estandar (R18): on_time NULL y una alerta missing_standard por plan y ruta mientras siga abierta.
CREATE OR REPLACE FUNCTION public.cl_transfer_sample(p_sample_id uuid)
 RETURNS uuid
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path = public, extensions
AS $$
DECLARE
  v_s    public.cl_samples;
  v_plan public.cl_plans;
  v_std  public.delivery_standards;
  v_eq_h numeric;
  v_eq_d integer;
  v_id   uuid;
  v_route jsonb;
BEGIN
  SELECT * INTO v_s FROM public.cl_samples WHERE id = p_sample_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'sample not found' USING ERRCODE = '22023'; END IF;
  SELECT * INTO v_plan FROM public.cl_plans WHERE id = v_s.plan_id;

  SELECT ds.* INTO v_std FROM public.delivery_standards ds
   WHERE ds.account_id = v_s.account_id AND ds.carrier_id = v_s.carrier_id AND ds.product_id = v_s.product_id
     AND ds.origin_city_id = v_s.origin_city_id AND ds.destination_city_id = v_s.destination_city_id
   ORDER BY ds.updated_at DESC NULLS LAST, ds.id
   LIMIT 1;
  IF v_std.id IS NOT NULL THEN
    SELECT e.eq_hours, e.eq_days INTO v_eq_h, v_eq_d FROM public.cl_equivalence(v_std.id) e;
  END IF;

  INSERT INTO public.one_db (account_id, allocation_detail_id, tag_id, plan_name, carrier_name, product_name,
                             origin_city_name, destination_city_name, sent_at, received_at, source_data_snapshot,
                             source, cl_sample_id, carrier_id, equivalence_hours, equivalence_days)
  SELECT v_s.account_id, NULL, v_s.item_id, v_plan.plan_name,
         (SELECT c.name FROM public.carriers c WHERE c.id = v_s.carrier_id),
         (SELECT p.description FROM public.products p WHERE p.id = v_s.product_id),
         (SELECT c.name FROM public.cities c WHERE c.id = v_s.origin_city_id),
         (SELECT c.name FROM public.cities c WHERE c.id = v_s.destination_city_id),
         v_s.start_at, v_s.end_at,
         jsonb_build_object('sample_id', v_s.id, 'plan_id', v_s.plan_id,
                            'start_reader_id', v_s.start_reader_id, 'end_reader_id', v_s.end_reader_id,
                            'origin_city_id', v_s.origin_city_id, 'destination_city_id', v_s.destination_city_id,
                            'extra', v_s.extra),
         'carrier', v_s.id, v_s.carrier_id, v_eq_h, v_eq_d
  RETURNING id INTO v_id;

  IF v_std.id IS NOT NULL AND v_std.standard_time IS NOT NULL THEN
    UPDATE public.one_db o
       SET on_time_delivery = public.one_db_on_time(o.business_transit_hours, o.business_transit_days,
                                                    v_std.standard_time, v_std.time_unit)
     WHERE o.id = v_id;
  ELSE
    v_route := jsonb_build_object('carrier_id', v_s.carrier_id, 'product_id', v_s.product_id,
                                  'origin_city_id', v_s.origin_city_id, 'destination_city_id', v_s.destination_city_id);
    -- Una alerta por plan y ruta (no por muestra). cl_raise_alert agrupa por cuota y dia, y una ruta real puede no
    -- tener cuota (envio mal encaminado) o compartirla con otra ruta; por eso la ruta va en details y se agrupa por ella.
    PERFORM pg_advisory_xact_lock(hashtext('cl_missing_standard:' || v_s.plan_id::text || ':' || v_route::text));
    IF NOT EXISTS (SELECT 1 FROM public.cl_alerts a
                    WHERE a.plan_id = v_s.plan_id AND a.alert_type = 'missing_standard' AND a.status = 'open'
                      AND a.details @> v_route) THEN
      INSERT INTO public.cl_alerts (account_id, plan_id, batch_id, quota_id, alert_type, severity, details)
      VALUES (v_s.account_id, v_s.plan_id, v_s.batch_id, NULL, 'missing_standard', 'high',
              v_route || jsonb_build_object('first_sample_id', v_s.id,
                                            'standard_id', v_std.id));
    END IF;
  END IF;
  RETURN v_id;
END $$;
REVOKE ALL ON FUNCTION public.cl_transfer_sample(uuid) FROM PUBLIC, anon, authenticated, service_role;

-- ---------------------------------------------------------------- resumen de un sorteo (desde cl_sampling_runs)
CREATE OR REPLACE FUNCTION public.cl_run_summary(p_run public.cl_sampling_runs)
 RETURNS jsonb
 LANGUAGE sql
 IMMUTABLE
 SET search_path = public, extensions
AS $$
  SELECT jsonb_build_object('batch_id', p_run.batch_id, 'stratum_id', p_run.stratum_id,
                            'population_size', p_run.population_size, 'candidates_valid', p_run.candidates_valid,
                            'samples_required', p_run.samples_required, 'samples_selected', p_run.samples_selected,
                            'selected_item_ids', to_jsonb(p_run.selected_item_ids), 'executed_at', p_run.executed_at)
$$;
REVOKE ALL ON FUNCTION public.cl_run_summary(public.cl_sampling_runs) FROM PUBLIC, anon, authenticated, service_role;

-- ---------------------------------------------------------------- sorteo de un estrato
-- Orden: md5(semilla || ':' || item_id), desempate item_id COLLATE "C"; se toman los primeros samples_required
-- (el valor de la foto de la demanda). Semilla = cl_demands.random_seed, fijada al emitir (D10). La semilla no se
-- devuelve (queda en cl_sampling_runs para el auditor).
CREATE OR REPLACE FUNCTION public.cl_sample_stratum(p_batch_id uuid, p_stratum_id uuid)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path = public, extensions
AS $$
DECLARE
  v_batch  public.cl_batches;
  v_demand public.cl_demands;
  v_plan   public.cl_plans;
  v_quota  public.cl_plan_quotas;
  v_run    public.cl_sampling_runs;
  v_snap   jsonb;
  v_pop    integer;
  v_req    integer;
  v_valid  integer;
  v_sel    text[];
  v_item   text;
  v_sid    uuid;
  v_st     record;
  v_mis    jsonb := '[]'::jsonb;
  v_n      bigint;
  v_all_ok boolean;
BEGIN
  -- Serializa los sorteos de un mismo lote.
  SELECT * INTO v_batch FROM public.cl_batches WHERE id = p_batch_id FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'CL_BATCH_NOT_FOUND: batch not found' USING ERRCODE = '22023';
  END IF;

  -- Idempotente por (lote, estrato).
  SELECT * INTO v_run FROM public.cl_sampling_runs WHERE batch_id = p_batch_id AND stratum_id = p_stratum_id;
  IF FOUND THEN
    RETURN public.cl_run_summary(v_run);
  END IF;

  IF v_batch.status <> 'validated' THEN
    RAISE EXCEPTION 'CL_BATCH_NOT_VALIDATED: batch is %', v_batch.status USING ERRCODE = '22023';
  END IF;
  SELECT (e->>'population_size')::integer INTO v_pop
    FROM jsonb_array_elements(v_batch.summary->'strata') e WHERE e->>'stratum_id' = p_stratum_id::text;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'CL_UNKNOWN_STRATUM: stratum is not part of this batch' USING ERRCODE = '22023';
  END IF;

  SELECT * INTO v_demand FROM public.cl_demands WHERE id = v_batch.demand_id;
  SELECT * INTO v_plan FROM public.cl_plans WHERE id = v_demand.plan_id;
  SELECT * INTO v_quota FROM public.cl_plan_quotas WHERE id = p_stratum_id;
  SELECT sn.d INTO v_snap FROM jsonb_array_elements(v_demand.payload->'strata') sn(d)
   WHERE sn.d->>'stratum_id' = p_stratum_id::text;
  v_req := GREATEST(COALESCE((v_snap->>'samples_required')::integer, 0), 0);

  DROP TABLE IF EXISTS pg_temp.cl_sampler_rows;
  CREATE TEMP TABLE cl_sampler_rows ON COMMIT DROP AS
    SELECT * FROM public.cl_stratum_endpoints(p_batch_id, p_stratum_id);

  -- Candidatos: item_id con inicio y fin; los que ya son muestra activa del carrier (p. ej. el mismo envio en otro
  -- estrato del mismo lote) se descartan como en D12.
  SELECT count(*) INTO v_valid FROM (
    SELECT DISTINCT r.item_id FROM pg_temp.cl_sampler_rows r
     WHERE r.start_scan_id IS NOT NULL AND r.end_scan_id IS NOT NULL
       AND NOT EXISTS (SELECT 1 FROM public.cl_samples sm
                        WHERE sm.account_id = v_plan.account_id AND sm.carrier_id = v_plan.carrier_id
                          AND sm.item_id = r.item_id AND sm.status = 'active')) c;

  SELECT COALESCE(array_agg(c.item_id ORDER BY c.k, c.item_id COLLATE "C"), ARRAY[]::text[]) INTO v_sel
    FROM (SELECT c0.item_id, md5(v_demand.random_seed || ':' || c0.item_id) AS k
            FROM (SELECT DISTINCT r.item_id FROM pg_temp.cl_sampler_rows r
                   WHERE r.start_scan_id IS NOT NULL AND r.end_scan_id IS NOT NULL
                     AND NOT EXISTS (SELECT 1 FROM public.cl_samples sm
                                      WHERE sm.account_id = v_plan.account_id AND sm.carrier_id = v_plan.carrier_id
                                        AND sm.item_id = r.item_id AND sm.status = 'active')) c0
           ORDER BY k, c0.item_id COLLATE "C"
           LIMIT v_req) c;

  FOREACH v_item IN ARRAY v_sel LOOP
    SELECT s.start_scan_id, s.end_scan_id INTO v_st FROM pg_temp.cl_sampler_rows s WHERE s.item_id = v_item LIMIT 1;

    INSERT INTO public.cl_samples (account_id, plan_id, quota_id, batch_id, carrier_id, product_id, item_id,
                                   start_reader_id, start_at, end_reader_id, end_at, origin_city_id, destination_city_id,
                                   extra)
    SELECT v_plan.account_id, v_plan.id, p_stratum_id, p_batch_id, v_plan.carrier_id, v_plan.product_id, v_item,
           a.reader_id, a.scan_at, z.reader_id, z.scan_at, a.city_id, z.city_id,
           COALESCE((SELECT jsonb_object_agg(x.key, x.value) FROM (
                       SELECT DISTINCT ON (e.key) e.key, e.value
                         FROM pg_temp.cl_sampler_rows r CROSS JOIN LATERAL jsonb_each(COALESCE(r.extra, '{}'::jsonb)) e
                        WHERE r.item_id = v_item
                        ORDER BY e.key, r.scan_at DESC, r.row_ord DESC) x), '{}'::jsonb)
      FROM pg_temp.cl_sampler_rows a, pg_temp.cl_sampler_rows z
     WHERE a.scan_id = v_st.start_scan_id AND z.scan_id = v_st.end_scan_id
    RETURNING id INTO v_sid;

    -- Todas sus lecturas de inicio y de fin (R15). Papel: las elegidas como inicio/fin; si no, segun el punto;
    -- un punto de inicio y fin a la vez cuenta como inicio hasta la hora del inicio elegido y como fin despues.
    INSERT INTO public.cl_sample_scans (account_id, sample_id, reader_id, scan_at, role, place_ref, mode_ref)
    SELECT v_plan.account_id, v_sid, r.reader_id, r.scan_at,
           CASE WHEN r.scan_id = r.start_scan_id THEN 'start'
                WHEN r.scan_id = r.end_scan_id THEN 'end'
                WHEN (r.is_start OR r.live_start) AND NOT (r.is_end OR r.live_end) THEN 'start'
                WHEN (r.is_end OR r.live_end) AND NOT (r.is_start OR r.live_start) THEN 'end'
                WHEN r.scan_at <= (SELECT a.scan_at FROM pg_temp.cl_sampler_rows a WHERE a.scan_id = r.start_scan_id) THEN 'start'
                ELSE 'end' END,
           r.place_ref, r.mode_ref
      FROM pg_temp.cl_sampler_rows r
     WHERE r.item_id = v_item AND (r.is_start OR r.is_end OR r.live_start OR r.live_end)
     ORDER BY r.row_ord;

    -- Posible mal encaminado (D5): mas de un punto de inicio, mas de un punto de fin, o ciudad distinta de la cuota.
    UPDATE public.cl_samples sm SET possible_misrouting = true
     WHERE sm.id = v_sid
       AND ((SELECT count(DISTINCT x.reader_id) FROM public.cl_sample_scans x WHERE x.sample_id = v_sid AND x.role = 'start') > 1
         OR (SELECT count(DISTINCT x.reader_id) FROM public.cl_sample_scans x WHERE x.sample_id = v_sid AND x.role = 'end') > 1
         OR sm.origin_city_id IS DISTINCT FROM v_quota.origin_city_id
         OR sm.destination_city_id IS DISTINCT FROM v_quota.destination_city_id);
    IF FOUND THEN
      v_mis := v_mis || jsonb_build_array(jsonb_build_object('sample_id', v_sid, 'item_id', v_item));
    END IF;

    PERFORM public.cl_transfer_sample(v_sid);
  END LOOP;

  -- Cuenta para la cuota de la que se extrajo, aunque sea un posible mal encaminado (R15).
  UPDATE public.cl_plan_quotas SET samples_obtained = samples_obtained + cardinality(v_sel) WHERE id = p_stratum_id;

  INSERT INTO public.cl_sampling_runs (account_id, demand_id, batch_id, stratum_id, population_size, candidates_valid,
                                       samples_required, samples_selected, random_seed, selected_item_ids)
  VALUES (v_plan.account_id, v_demand.id, p_batch_id, p_stratum_id, v_pop, v_valid, v_req, cardinality(v_sel),
          v_demand.random_seed, v_sel)
  RETURNING * INTO v_run;

  -- Alertas.
  IF v_valid < v_req THEN
    PERFORM public.cl_raise_alert(v_plan.id, p_stratum_id, 'insufficient_candidates', 'medium',
      jsonb_build_object('batch_id', p_batch_id, 'candidates_valid', v_valid, 'samples_required', v_req));
  END IF;
  IF jsonb_array_length(v_mis) > 0 THEN
    PERFORM public.cl_raise_alert(v_plan.id, p_stratum_id, 'possible_misrouting', 'medium',
      jsonb_build_object('batch_id', p_batch_id, 'samples', v_mis,
                         'item_ids', (SELECT jsonb_agg(m->'item_id') FROM jsonb_array_elements(v_mis) m)));
  END IF;
  -- Distribucion sospechosa: n >= 20 muestras de la cuota con "en plazo" y todas en plazo.
  SELECT count(*), bool_and(o.on_time_delivery) INTO v_n, v_all_ok
    FROM public.cl_samples sm JOIN public.one_db o ON o.cl_sample_id = sm.id
   WHERE sm.quota_id = p_stratum_id AND sm.status = 'active' AND o.on_time_delivery IS NOT NULL;
  IF v_n >= 20 AND v_all_ok THEN
    PERFORM public.cl_raise_alert(v_plan.id, p_stratum_id, 'suspicious_distribution', 'medium',
      jsonb_build_object('batch_id', p_batch_id, 'samples', v_n, 'on_time_ratio', 1));
  END IF;

  DROP TABLE pg_temp.cl_sampler_rows;
  RETURN public.cl_run_summary(v_run);
END $$;
REVOKE ALL ON FUNCTION public.cl_sample_stratum(uuid, uuid) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.cl_sample_stratum(uuid, uuid) TO service_role;

-- ---------------------------------------------------------------- cierre del lote
-- Cuando todos los estratos del lote (summary->strata) tienen cl_sampling_runs: lote 'sampled'; demanda 'fulfilled'
-- si cada estrato de la demanda obtuvo sus samples_required en este lote, si no 'partial'; cuotas del lote que ya
-- tienen lo previsto + arrastrado -> 'fulfilled' (las demas siguen 'open'; la tarea 9 las liquida).
-- Si falta algun estrato no cambia nada y devuelve status 'pending' con los estratos que faltan. Idempotente.
CREATE OR REPLACE FUNCTION public.cl_finish_batch(p_batch_id uuid)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path = public, extensions
AS $$
DECLARE
  v_batch   public.cl_batches;
  v_demand  public.cl_demands;
  v_pending jsonb;
  v_status  text;
BEGIN
  SELECT * INTO v_batch FROM public.cl_batches WHERE id = p_batch_id FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'CL_BATCH_NOT_FOUND: batch not found' USING ERRCODE = '22023';
  END IF;
  SELECT * INTO v_demand FROM public.cl_demands WHERE id = v_batch.demand_id FOR UPDATE;

  IF v_batch.status = 'sampled' THEN
    RETURN jsonb_build_object('batch_id', p_batch_id, 'status', 'sampled', 'demand_status', v_demand.status,
                              'strata_pending', '[]'::jsonb);
  END IF;
  IF v_batch.status <> 'validated' THEN
    RAISE EXCEPTION 'CL_BATCH_NOT_VALIDATED: batch is %', v_batch.status USING ERRCODE = '22023';
  END IF;

  SELECT COALESCE(jsonb_agg(e->'stratum_id' ORDER BY o), '[]'::jsonb) INTO v_pending
    FROM jsonb_array_elements(v_batch.summary->'strata') WITH ORDINALITY x(e, o)
   WHERE NOT EXISTS (SELECT 1 FROM public.cl_sampling_runs r
                      WHERE r.batch_id = p_batch_id AND r.stratum_id::text = e->>'stratum_id');
  IF jsonb_array_length(v_pending) > 0 THEN
    RETURN jsonb_build_object('batch_id', p_batch_id, 'status', 'pending', 'demand_status', v_demand.status,
                              'strata_pending', v_pending);
  END IF;

  UPDATE public.cl_batches SET status = 'sampled' WHERE id = p_batch_id;

  v_status := CASE WHEN NOT EXISTS (
                  SELECT 1 FROM jsonb_array_elements(v_demand.payload->'strata') d
                   WHERE NOT EXISTS (SELECT 1 FROM public.cl_sampling_runs r
                                      WHERE r.batch_id = p_batch_id AND r.stratum_id::text = d->>'stratum_id'
                                        AND r.samples_selected >= COALESCE((d->>'samples_required')::integer, 0)))
                THEN 'fulfilled' ELSE 'partial' END;
  IF v_demand.status = 'open' THEN
    UPDATE public.cl_demands SET status = v_status WHERE id = v_demand.id;
  ELSE
    v_status := v_demand.status;
  END IF;

  UPDATE public.cl_plan_quotas q SET status = 'fulfilled'
   WHERE q.id IN (SELECT r.stratum_id FROM public.cl_sampling_runs r WHERE r.batch_id = p_batch_id)
     AND q.status = 'open'
     AND q.samples_obtained >= q.samples_planned + q.samples_carried_in;

  RETURN jsonb_build_object('batch_id', p_batch_id, 'status', 'sampled', 'demand_status', v_status,
                            'strata_pending', '[]'::jsonb);
END $$;
REVOKE ALL ON FUNCTION public.cl_finish_batch(uuid) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.cl_finish_batch(uuid) TO service_role;
