-- Carrier Link DEMO2 synthetic test, phase "setup" step a (WRITES; one transaction; idempotent).
-- Target: DEMO2 (f4d823d2-93e6-4755-9a89-9da87e7fa86e) in project sehbnpgzqljrsqimwyuz, or the local onems_t copy.
-- Creates, on DEMO2's REAL masters (Carrier A / A STANDARD / New York, Baltimore, Philadelphia):
--   * 7 carrier reading points (readers.capture_source = 'carrier_scan') in 4 existing postal centers;
--   * 1 connector cl_feeds 'Carrier A - Carrier Link DEMO' (status testing, emits any day; hour set by 30_emit.sql);
--   * 5 field mappings, 1 product value mapping (STD -> A STANDARD), 1 allowed extra field (weight_kg);
--   * equivalence (cl_last_mile_time = 1 day) on the 2 existing standards NY->BAL and BAL->NY, ONLY if both
--     equivalence columns are still 0. Reporting-only (D9); panelist on_time is recomputed by the existing trigger
--     with the same standard_time, so it does not change (inspect/09_std_drift.sql = 0 rows would change).
-- Fixed ids (prefix c1de2000-) so later phases and the cleanup find everything.
DO $$
DECLARE
  c_acc  constant uuid := 'f4d823d2-93e6-4755-9a89-9da87e7fa86e';
  c_car  constant uuid := '856b4a5c-1716-4110-ac5e-0d7c909b9237';  -- Carrier A (code 'CARRIER A ')
  c_prod constant uuid := '8325a692-7e1c-40a6-9a54-59527d19634f';  -- A STANDARD
  c_feed constant uuid := 'c1de2000-0000-4000-8000-0000000000f1';
  v_n integer;
BEGIN
  -- Guards: right account and the expected live masters.
  IF (SELECT slug FROM public.accounts WHERE id = c_acc) IS DISTINCT FROM 'DEMO2' THEN
    RAISE EXCEPTION 'GUARD: account % is not DEMO2', c_acc;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM public.carriers WHERE id = c_car AND account_id = c_acc)
     OR NOT EXISTS (SELECT 1 FROM public.products WHERE id = c_prod AND carrier_id = c_car AND btrim(code) = 'A STANDARD') THEN
    RAISE EXCEPTION 'GUARD: Carrier A / A STANDARD not found in DEMO2';
  END IF;
  SELECT count(*) INTO v_n FROM public.postal_centers
   WHERE account_id = c_acc AND city_id IS NOT NULL
     AND id IN ('5c1ef79d-c57d-41fa-aa2d-f38d9611ea2a', '3cb1d5b8-2785-4d66-9a7a-6ce24909b1fc',
                'c395d565-e731-4d93-baf9-383a15d59568', '117f06f9-5ed5-4e40-b104-5e8f0baa8884');
  IF v_n <> 4 THEN RAISE EXCEPTION 'GUARD: expected 4 DEMO2 postal centers with city, found %', v_n; END IF;

  -- Reading points (carrier place = facility_id, carrier mode = event_code). reader_id is generated by trigger:
  -- CL:DEMO2:CARRIER A :<place>[:<mode>].
  INSERT INTO public.readers (id, account_id, postal_center_id, reader_id, name, description, type,
                              capture_source, carrier_id, carrier_place_ref, carrier_mode_ref, e2e_role)
  SELECT x.id::uuid, c_acc, x.pc::uuid, 'CL', x.name, 'Carrier Link DEMO (synthetic test)', x.type,
         'carrier_scan', c_car, x.place, x.mode, x.role
    FROM (VALUES
      ('c1de2000-0000-4000-8000-000000000101', '5c1ef79d-c57d-41fa-aa2d-f38d9611ea2a', 'Carrier A NYC-RDC acceptance', 'Entry', 'NYC-RDC', 'ACC', 'origin'),
      ('c1de2000-0000-4000-8000-000000000102', '5c1ef79d-c57d-41fa-aa2d-f38d9611ea2a', 'Carrier A NYC-RDC dispatch',   'Exit',  'NYC-RDC', 'DSP', 'none'),
      ('c1de2000-0000-4000-8000-000000000103', '3cb1d5b8-2785-4d66-9a7a-6ce24909b1fc', 'Carrier A NYC-LDC delivery',   'Exit',  'NYC-LDC', 'DLV', 'destination'),
      ('c1de2000-0000-4000-8000-000000000104', 'c395d565-e731-4d93-baf9-383a15d59568', 'Carrier A BAL-PC acceptance',  'Entry', 'BAL-PC',  'ACC', 'origin'),
      ('c1de2000-0000-4000-8000-000000000105', 'c395d565-e731-4d93-baf9-383a15d59568', 'Carrier A BAL-PC dispatch',    'Exit',  'BAL-PC',  'DSP', 'none'),
      ('c1de2000-0000-4000-8000-000000000106', 'c395d565-e731-4d93-baf9-383a15d59568', 'Carrier A BAL-PC delivery',    'Exit',  'BAL-PC',  'DLV', 'destination'),
      ('c1de2000-0000-4000-8000-000000000107', '117f06f9-5ed5-4e40-b104-5e8f0baa8884', 'Carrier A PHL-RH (any event)', 'Exit',  'PHL-RH',  NULL,  'destination')
    ) x(id, pc, name, type, place, mode, role)
   WHERE NOT EXISTS (SELECT 1 FROM public.readers r WHERE r.id = x.id::uuid);

  INSERT INTO public.cl_feeds (id, account_id, carrier_id, name, extraction_model, config, status, emit_days, emit_hour)
  VALUES (c_feed, c_acc, c_car, 'Carrier A - Carrier Link DEMO', 'push_api',
          '{"note": "synthetic test connector (supabase/tests/adhoc/cl_demo2)"}'::jsonb, 'testing', '{1,2,3,4,5,6,7}', 3)
  ON CONFLICT (id) DO NOTHING;

  INSERT INTO public.cl_field_mappings (account_id, carrier_id, standard_field, carrier_field, format, timezone) VALUES
    (c_acc, c_car, 'item_id',   'tracking_number', NULL, NULL),
    (c_acc, c_car, 'product',   'service_code',    NULL, NULL),
    (c_acc, c_car, 'scan_at',   'event_time',      'YYYY-MM-DD HH24:MI:SS', 'America/New_York'),
    (c_acc, c_car, 'place_ref', 'facility_id',     NULL, NULL),
    (c_acc, c_car, 'mode_ref',  'event_code',      NULL, NULL)
  ON CONFLICT (account_id, carrier_id, standard_field) DO NOTHING;

  INSERT INTO public.cl_value_mappings (account_id, carrier_id, kind, carrier_value, onems_value)
  VALUES (c_acc, c_car, 'product', 'STD', 'A STANDARD')
  ON CONFLICT (account_id, carrier_id, kind, carrier_value) DO NOTHING;

  INSERT INTO public.cl_extra_fields (account_id, carrier_id, carrier_field)
  VALUES (c_acc, c_car, 'weight_kg')
  ON CONFLICT (account_id, carrier_id, carrier_field) DO NOTHING;

  -- Equivalence on the two routes that have a standard (only when untouched: both columns 0).
  UPDATE public.delivery_standards
     SET cl_last_mile_time = 1
   WHERE account_id = c_acc
     AND id IN ('8afdb952-be52-450b-ac44-323f9c2973e3',   -- New York -> Baltimore, A STANDARD, 4 days
                '79c2d399-1e46-44bd-b6d5-799af726ef03')   -- Baltimore -> New York, A STANDARD, 4 days
     AND cl_first_mile_time = 0 AND cl_last_mile_time = 0;
END $$;

SELECT jsonb_build_object(
  'readers', (SELECT jsonb_agg(jsonb_build_object('reader_id', r.reader_id, 'role', r.e2e_role, 'type', r.type) ORDER BY r.id)
                FROM public.readers r WHERE r.id::text LIKE 'c1de2000-%'),
  'feed', (SELECT jsonb_build_object('status', f.status, 'emit_days', f.emit_days, 'emit_hour', f.emit_hour)
             FROM public.cl_feeds f WHERE f.id = 'c1de2000-0000-4000-8000-0000000000f1'),
  'field_mappings', (SELECT count(*) FROM public.cl_field_mappings WHERE account_id = 'f4d823d2-93e6-4755-9a89-9da87e7fa86e'),
  'value_mappings', (SELECT count(*) FROM public.cl_value_mappings WHERE account_id = 'f4d823d2-93e6-4755-9a89-9da87e7fa86e'),
  'extra_fields', (SELECT count(*) FROM public.cl_extra_fields WHERE account_id = 'f4d823d2-93e6-4755-9a89-9da87e7fa86e'),
  'standards', (SELECT jsonb_agg(jsonb_build_object('id', id, 'first', cl_first_mile_time, 'last', cl_last_mile_time) ORDER BY id)
                  FROM public.delivery_standards
                 WHERE id IN ('8afdb952-be52-450b-ac44-323f9c2973e3', '79c2d399-1e46-44bd-b6d5-799af726ef03'))
) AS step_a;
